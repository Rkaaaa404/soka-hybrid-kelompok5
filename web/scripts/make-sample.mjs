// Builds src/sim/sample.ts: a 30-task GoCJ window used by the in-browser HMMGA lab.
// The window (GoCJ_Dataset_5000, rows 930-959) was picked with scripts/search-window.mjs because Max-Min
// is not already optimal there, so both the migration step and the GA have something to improve.
// Arrival times are rebased so the first task arrives at t = 0; lengths in MI.
import { readFileSync, writeFileSync } from 'node:fs';

const N = 30;
const START = 930;
const FILE = 'GoCJ_Dataset_5000.csv';

const csv = readFileSync(new URL(`../../dataset/${FILE}`, import.meta.url), 'utf8');
const lines = csv
  .trim()
  .split(/\r?\n/)
  .slice(START, START + N)
  .map((l) => l.split(',').map(Number));
const t0 = lines[0][2];
const rows = lines.map(([len, sla, arrival], id) => ({ id, lengthMi: len, sla, arrivalTime: arrival - t0 }));

const out = `// Generated by scripts/make-sample.mjs from dataset/${FILE} (rows ${START}-${START + N - 1}, arrivals rebased).
import type { LabTask } from './types';

export const SAMPLE_TASKS: LabTask[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../src/sim/sample.ts', import.meta.url), out);
console.log(`wrote ${rows.length} tasks from ${FILE} rows ${START}-${START + N - 1}`);
